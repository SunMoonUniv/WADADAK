package com.wadadak.course.internal.explore;

/** 코스 목록 정렬(FIL-01). 정렬 값이 모두 같으면 코스 ID순이다. */
enum CourseListSort {
    /**
     * 인기순: 도전 수(코스 러닝을 실제로 시작한 세션 수)가 많은 코스부터. 같으면 조회 수, 리뷰 수가 많은 코스, 그다음 최신순.
     * 기간(FIL-09)을 주면 그 기간의 도전 수 · 조회 수 · 리뷰 수로 정한다. 기간에 값이 없는 코스도 빠지지 않고 뒤에 온다.
     */
    POPULAR,
    /**
     * 평점순: 전체 기간 평점(소수 첫째 자리 반올림, 카드에 보이는 값)이 높은 코스부터. 같으면 리뷰 수가 많은 코스, 그다음 최신순.
     * 리뷰가 없는 코스는 맨 뒤다.
     */
    RATING,
    /** 가까운순: 현재 위치에서 출발점까지 가까운 코스부터 */
    NEAREST,
    /** 최신순: 등록 시각이 늦은 코스부터 */
    LATEST,
    /** 실시간순: 지금 달리는 러너가 많은 코스부터. 같으면 인기순(전체 기간) 순서다 */
    LIVE
}
